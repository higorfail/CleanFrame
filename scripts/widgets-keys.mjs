// Development only: store personal widget keys in ignored .local/ files.
//   npm run widgets:keys -- spotify <client-id>     Spotify login (PKCE) on this computer
//   npm run widgets:keys -- stremio                 Stremio login → auth key
//   npm run widgets:keys -- set tmdb.apiKey <key>   Any other value (smartthings.token, smartthings.lightId, pluto.channel…)
//   npm run widgets:keys -- show                    Which keys are set (values hidden)
// Keys go to .local/widgets-secrets.json and .local/widgets-secrets.js; private previews and
// personal packages inject them as widgets/secrets.js. Public exports never include them.
import { createServer } from 'node:http';
import { createHash, randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync, chmodSync } from 'node:fs';
import { createInterface } from 'node:readline/promises';
import { root } from './browser.mjs';

const dir = root + '.local/', json = dir + 'widgets-secrets.json', js = dir + 'widgets-secrets.js';
const load = () => existsSync(json) ? JSON.parse(readFileSync(json, 'utf8')) : {};
function save(values) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(json, JSON.stringify(values, null, 2) + '\n'); chmodSync(json, 0o600);
  writeFileSync(js, '/* Generated by npm run widgets:keys. Private: never commit or publish. */\n(function (c, s) {\n' +
    '  if (!c) return;\n  Object.keys(s).forEach(function (group) {\n    if (typeof s[group] !== "object" || !c[group]) { c[group] = s[group]; return; }\n' +
    '    Object.keys(s[group]).forEach(function (key) { c[group][key] = s[group][key]; });\n  });\n}(window.FrameWidgetsConfig, ' +
    JSON.stringify(values) + '));\n');
  chmodSync(js, 0o600);
}
function set(path, value) {
  const values = load(), [group, key] = path.split('.');
  if (!group) throw Error('Use group.key, for example tmdb.apiKey');
  if (key) { values[group] = values[group] || {}; values[group][key] = value; } else values[group] = value;
  save(values);
}

const [command, ...args] = process.argv.slice(2);
if (command === 'set') {
  if (args.length < 2) throw Error('Usage: set <group.key> <value>');
  set(args[0], args.slice(1).join(' '));
  console.log('Saved ' + args[0] + '.');
} else if (command === 'show') {
  const values = load();
  for (const group of Object.keys(values)) for (const key of Object.keys(values[group] || {})) console.log(group + '.' + key + ': ' + (values[group][key] ? 'set' : 'empty'));
  if (!Object.keys(values).length) console.log('No widget keys yet.');
} else if (command === 'spotify') {
  const clientId = args[0];
  if (!clientId) throw Error('Usage: spotify <client-id>  (create an app at developer.spotify.com with redirect URI http://127.0.0.1:8888/callback)');
  const verifier = randomBytes(48).toString('base64url'), challenge = createHash('sha256').update(verifier).digest('base64url');
  const redirect = 'http://127.0.0.1:8888/callback', state = randomBytes(8).toString('hex');
  const scope = 'user-read-currently-playing user-read-playback-state user-modify-playback-state user-read-recently-played';
  const url = 'https://accounts.spotify.com/authorize?' + new URLSearchParams({ client_id: clientId, response_type: 'code', redirect_uri: redirect,
    code_challenge_method: 'S256', code_challenge: challenge, scope, state });
  console.log('Open this address in your browser and allow access:\n\n' + url + '\n');
  const code = await new Promise((resolve, reject) => {
    const server = createServer((req, res) => {
      const q = new URL(req.url, redirect).searchParams;
      if (!req.url.startsWith('/callback')) { res.end(); return; }
      res.end(q.get('code') ? 'Spotify connected. You can close this tab.' : 'Spotify did not return a code.');
      server.close();
      if (q.get('state') !== state || !q.get('code')) reject(Error('Spotify login was cancelled.')); else resolve(q.get('code'));
    }).listen(8888, '127.0.0.1');
  });
  const response = await fetch('https://accounts.spotify.com/api/token', { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({ grant_type: 'authorization_code', code, redirect_uri: redirect, client_id: clientId, code_verifier: verifier }) });
  const token = await response.json();
  if (!token.refresh_token) throw Error('Spotify did not return a refresh token: ' + (token.error_description || token.error || response.status));
  set('spotify.clientId', clientId); set('spotify.refreshToken', token.refresh_token);
  console.log('Spotify connected. Package and install again to send it to the TV.');
} else if (command === 'stremio') {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const email = await rl.question('Stremio e-mail: ');
  const password = await rl.question('Stremio password (not stored): ');
  rl.close();
  const response = await fetch('https://api.strem.io/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ type: 'Login', email, password, facebook: false }) });
  const body = await response.json();
  const key = body && body.result && body.result.authKey;
  if (!key) throw Error('Stremio login failed: ' + JSON.stringify(body && body.error || response.status));
  set('stremio.authKey', key);
  console.log('Stremio connected. Package and install again to send it to the TV.');
} else {
  console.log('Commands: spotify <client-id> | stremio | set <group.key> <value> | show');
}
